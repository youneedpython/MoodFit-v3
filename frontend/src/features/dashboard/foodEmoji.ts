/** 이름의 음식 낱말로 고르는 장식 아이콘. 구체적인 메뉴를 먼저 검사한다. */
const FOOD_EMOJI: [string, string][] = [
  ["샐러드", "🥗"], ["샌드위치", "🥪"], ["파스타", "🍝"],
  ["국수", "🍜"], ["우동", "🍜"], ["스튜", "🍲"], ["수프", "🍲"],
  ["만둣국", "🥟"], ["김밥", "🍙"], ["주먹밥", "🍙"],
  ["비빔밥", "🍚"], ["덮밥", "🍚"], ["볶음밥", "🍚"], ["보리밥", "🍚"],
  ["라이스볼", "🍚"], ["죽", "🥣"], ["오트밀", "🥣"], ["요거트", "🥣"],
  ["쿠스쿠스", "🥣"], ["달걀", "🥚"], ["콩", "🫘"], ["차", "🍵"],
];

export function foodEmoji(name: string): string {
  return FOOD_EMOJI.find(([word]) => name.includes(word))?.[1] ?? "🍽️";
}
